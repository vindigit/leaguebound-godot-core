'use strict';
// Presentation only; all judgments are retained by the independent recount.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..'), directory = path.join(root, 'analysis/stage4_blocker_review');
const x = JSON.parse(fs.readFileSync(path.join(directory, 'blocker_recount.json'), 'utf8'));
const f = n => Number.isFinite(n) ? Number(n.toPrecision(8)).toString() : 'unavailable';
const interval = e => {
  if (Array.isArray(e.interval)) return '[' + e.interval.map(f).join(', ') + ']';
  if (e.interval && typeof e.interval === 'object') return '[' + f(e.interval.low) + ', ' + f(e.interval.high) + ']';
  return 'unavailable';
};
let text = '# Stage 4 blocker measurements\n\nGenerated by `node tools/render_stage4_blocker_tables.cjs` from `blocker_recount.json`.\n\n' +
  'Fresh canonical: **200 complete games, 40 per competition**, seeds 1–40, source `' + x.current.context.commit_sha +
  '`. 98 metrics, 74 judged, **nine FAIL**, with all 92 aggregation-backed estimates independently recomputed. ' +
  'The same prefix was used previously; this is a reproducibility run, not an untouched validation sample.\n\n' +
  'Corrected pairing A/B reuse 4,680 archived games across five competitions (468 each per range; 117 quartets). ' +
  'Reused controlled venue evidence has 1,000 complete triples / 3,000 games. No new sample is implied by recounting.\n\n' +
  '**Interval warning:** canonical proportion intervals retain a proven reporting defect: Wilson half-widths are recentered on the raw estimate. ' +
  'For 0/40, the printed interval is [-0.0438108012, 0.0438108012], while Wilson endpoints are [0, 0.0876216025]. ' +
  'FG% has an explicit team-game ratio-width override. Historical endpoints below are preserved, not endorsed as correct Wilson coverage. ' +
  'The new Builder/OVR analyses use separately declared cluster methods.\n\n' +
  '## Fresh nine failures\n\n| Metric | Exact contract / band | Estimate | Raw ratio or sample | Existing interval |\n| --- | --- | ---: | --- | --- |\n';
for (const m of x.current.failures) {
  const a = m.aggregation;
  text += `| ${m.metric} | ${m.target.source}; ${f(m.target.minimum)}–${f(m.target.maximum)} | ${f(m.estimate)} | ` +
    (a && ['ratio', 'proportion'].includes(a.kind) ? `${f(a.numerator)}/${f(a.denominator)}${a.scale !== 1 ? ' × ' + f(a.scale) : ''}`
      : `${m.sample_count} ${m.denominator}`) + ` | ${interval({interval: m.interval_95})} |\n`;
}
text += '\n## Every supported failed metric ID\n\n' +
  'Nineteen IDs are retained across the fresh canonical, the two corrected candidate home arms, and the legacy venue failure. ' +
  'A passing small cell never erases a larger recorded miss. Intervals for corrected A/B are conditional exploratory quartet intervals, unadjusted across metrics; ' +
  'the canonical report uses its existing interval definitions. No interval below is a certification result.\n\n' +
  '| Metric | Contract | Fresh estimate | Corrected A estimate [interval] | Corrected B estimate [interval] | Classification |\n' +
  '| --- | --- | --- | --- | --- | --- |\n';
for (const r of x.failed_verdict_registry) {
  const target = r.evidence[0].target;
  const values = ['fresh canonical', 'validation_a corrected pairing, reused evidence', 'validation_b corrected pairing, reused evidence'].map(kind => {
    const e = r.evidence.find(e => e.kind === kind);
    return e ? `${f(e.estimate)} ${interval(e)}` : 'no failed verdict';
  });
  text += `| ${r.metric} | ${target.source}; ${f(target.minimum)}–${f(target.maximum)} | ${values.join(' | ')} | ${r.category} |\n`;
}
text += '\nEvery registry row retains affected competition, exact target, denominator/raw counts where available, sample, interval, source hashes, and next action in `blocker_recount.json`. ' +
  '`no failed verdict` means that row was not recorded as FAIL in that source; it does not claim missing measurements are passes.\n\n' +
  '## Controlled venue versus population outcomes\n\n' +
  '| Competition | Controlled attributable win rate | Controlled points/100 | Canonical paired cap | Legacy points/100 | Legacy failed rows |\n' +
  '| --- | ---: | ---: | --- | ---: | --- |\n';
for (const [comp, v] of Object.entries(x.venue)) text += `| ${comp} | ${f(v.controlled_win.estimate)} | ${f(v.paired_points_per100.estimate)} | ${v.controlled_cap.verdict} | ${f(v.legacy_points_per100.estimate)} | ${v.failed_metrics.map(m => m.metric).join(', ') || 'none'} |\n`;
text += '\nEach venue competition has 200 matched fixtures on seeds 710001–710200, mirror rosters, environment 0.5 and the unchanged v17/v2 rules. ' +
  'All controlled paired win point estimates meet 0.53–0.56 and all canonical paired caps meet +2.5 points/100. ' +
  'Overseas legacy `home.combined_cap_respected` still FAILS: 2.6321643 points/100, while its canonical paired reading is 1.9445731. ' +
  'Neither definition is substituted for the other. The legacy fail is a measurement-definition/reporting blocker; controlled passes at this small, reused diagnosis sample do not certify home court.\n';
fs.writeFileSync(path.join(directory, 'MEASUREMENTS.md'), text);
