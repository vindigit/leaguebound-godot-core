"""Render validated aggregate evidence without adding analytical decisions.

Python standard library only. Every number is an existing summary field; this
presentation utility does not recalculate rates, uncertainty or verdicts.
"""
from __future__ import annotations
import argparse
import json
import pathlib

from analyze import PRIMARY_IDS, SECONDARY_IDS

ROOT = pathlib.Path(__file__).resolve().parent
RANGES = ("validation_a", "validation_b")
OFFENSE = {
    "eFG %": "effective_field_goal_percentage",
    "Points /32 min": "points_per_32_minutes",
    "Created FG /100 touches": "created_field_goals_per_100_touches",
    "TO /100 touches (lower)": "turnovers_per_100_touches",
    "Advantages /100 touches": "advantages_per_100_touches",
    "Team margin /game": "team_margin_per_game",
}
DEFENSE = {
    "Steals /100 def poss": "steals_per_100_on_court_defense_possessions",
    "Blocks /100 def poss": "blocks_per_100_on_court_defense_possessions",
    "ORB /100 off poss": "offensive_rebounds_per_100_on_court_offense_possessions",
    "DRB /100 def poss": "defensive_rebounds_per_100_on_court_defense_possessions",
    "Primary-defender allowed eFG % (lower)": "allowed_effective_field_goal_percentage",
}


def number(value: float | None, decimals: int = 2) -> str:
    return "unavailable" if value is None else f"{value:.{decimals}f}"


def table(headers: list[str], rows: list[list[str]]) -> str:
    return "\n".join(["| " + " | ".join(headers) + " |",
                       "| " + " | ".join("---" for _ in headers) + " |"] +
                      ["| " + " | ".join(row) + " |" for row in rows])


def pair(summaries: list[dict], key: str) -> str:
    return " / ".join(number(s["metrics"][key]) for s in summaries)


def rates(builds: dict[str, list[dict]], definitions: dict[str, str]) -> str:
    return table(["Build"] + [label + " A / B" for label in definitions],
                 [[f"`{b}`"] + [pair(s, key) for key in definitions.values()]
                  for b, s in builds.items()])


def raw_counts(summaries: list[dict], keys: tuple[str, ...]) -> str:
    return " ; ".join("/".join(str(int(s["raw"][k])) for k in keys) for s in summaries)


def volume(builds: dict[str, list[dict]]) -> str:
    headers = ["Build", "Minutes/game A / B", "Points A ; B",
               "FGM/FGA/3PM A ; B", "FTM/FTA A ; B", "Touches A ; B",
               "On-court off/def possessions A ; B", "Defended makes/attempts A ; B"]
    rows = []
    for b, s in builds.items():
        rows.append([f"`{b}`", pair(s, "minutes_per_game"),
                     raw_counts(s, ("points",)),
                     raw_counts(s, ("field_goals_made", "field_goals_attempted", "three_pointers_made")),
                     raw_counts(s, ("free_throws_made", "free_throws_attempted")),
                     raw_counts(s, ("touches",)),
                     raw_counts(s, ("on_court_offense_possessions", "on_court_defense_possessions")),
                     raw_counts(s, ("defended_makes", "defended_attempts"))])
    return table(headers, rows)


def render(summary: dict) -> str:
    data = summary["ranges"]
    assert tuple(data) == RANGES, "render only both complete confirmation ranges"
    assert all(data[r]["games"] == 1184 for r in RANGES)
    primary = {b: [data[r]["summaries"][b] for r in RANGES] for b in PRIMARY_IDS}
    secondary = {"balanced_flat cell0": [data[r]["cells"]["balanced_flat"]["0"] for r in RANGES]}
    secondary.update({b: [data[r]["summaries"][b] for r in RANGES] for b in SECONDARY_IDS})
    blocks = ["# Builder confirmation aggregate tables",
              "Generated by `render_tables.py` from the validated `summary.json`. "
              "A/B identify the frozen validation ranges. Primary arms have 64 games "
              "and 16 matched quartets/range; separate cell 0 arms have 8 games and 2 quartets. "
              "All numbers below are existing aggregate fields; full precision, "
              "every raw counter, per-cell evidence and all 374 primary intervals "
              "remain in the summary. These tables are descriptive, not a certification.",
              "eFG and allowed eFG inherit the current missed-shooting-foul FGA "
              "convention. On-court possession exposure is measured at possession "
              "start. Across-cell source/cap/roster changes prevent interpreting "
              "cell differences as an isolated same-player deployment effect.",
              "## Equal-resource primary wings: offense, contribution and team results",
              rates(primary, OFFENSE),
              "## Equal-resource primary wings: defense and rebounding",
              rates(primary, DEFENSE),
              "## Equal-resource primary wings: raw counts and opportunities",
              "Counts are totals over 64 games/range. FGM/FGA/3PM are field-goal "
              "makes/attempts/three-point makes. FTM/FTA are free-throw makes/attempts. "
              "The semicolon separates A and B; the slash separates fields.",
              volume(primary),
              "## Separate profile/family observations in cell 0",
              "These rows use 8 games/range and 2 quartets; no inferential intervals "
              "are available. Ready Now 235 AP and High Upside 155 AP are unequal "
              "resources versus Balanced 195 AP. Guard/big arms bundle family, body, "
              "position and deployment. Their common cell 0 reference is shown "
              "rather than the eight-cell primary mean.",
              rates(secondary, OFFENSE), rates(secondary, DEFENSE), volume(secondary),
              "## Raw archive fingerprints",
              "\n".join(f"- `{path}`: `{digest}`" for path, digest in summary["raw_sha256"].items())]
    return "\n\n".join(blocks) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--summary", type=pathlib.Path, default=ROOT / "summary.json")
    parser.add_argument("--output", type=pathlib.Path, default=ROOT / "MEASUREMENTS.md")
    args = parser.parse_args()
    args.output.write_text(render(json.loads(args.summary.read_text(encoding="utf-8"))), encoding="utf-8")


if __name__ == "__main__":
    main()
